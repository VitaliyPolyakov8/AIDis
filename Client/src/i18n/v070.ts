type Tree = { [key: string]: string | Tree };

/** Deep merge of a base dictionary and an overlay (overlay wins on leaves). */
export function mergeDictionaries<T extends object>(base: T, overlay: object): T {
  const out: Tree = { ...(base as unknown as Tree) };
  for (const [key, value] of Object.entries(overlay as Tree)) {
    const current = out[key];
    out[key] = typeof value === 'object' && typeof current === 'object' ? mergeDictionaries(current, value) : value;
  }
  return out as unknown as T;
}
